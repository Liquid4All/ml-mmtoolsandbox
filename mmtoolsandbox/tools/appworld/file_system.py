@requires_auth("file_system")
def file_system_move_directory(
    source_directory_path: str,
    destination_directory_path: str,
    overwrite: bool | None = False,
    retain_dates: bool | None = False,
) -> dict[str, Any]:
    """
    Move a directory to another location.

    Args:
        source_directory_path: Path of the source directory. Path can be absolute, starting with '/', or relative to the user's home directory, starting with '~/'.
        destination_directory_path: Path of the destination directory. Path can be absolute, starting with '/', or relative to the user's home directory, starting with '~/'.
        overwrite: Whether to overwrite the directory if it already exists. (optional)
        retain_dates: Whether the files in the moved directory should retain the created and updated dates of the files in the original directory. (optional)

    Returns:
        Success: {"message": str, "destination_directory_path": str}
        Failure: {"message": str}
    """
    bridge = get_appworld_bridge()
    appworld_state = get_appworld_state()

    params: dict[str, Any] = {
        "access_token": appworld_state.get_access_token("file_system"),
        "source_directory_path": source_directory_path,
        "destination_directory_path": destination_directory_path,
    }
    if overwrite is not None:
        params["overwrite"] = overwrite
    if retain_dates is not None:
        params["retain_dates"] = retain_dates

    response = bridge.call_api("file_system", "move_directory", method="post", **params)

    if isinstance(response, dict) and "error" in response:
        raise ValueError(f"API error: {response['error']}")

    return dict(response) if isinstance(response, dict) else {}


