    if compressed_file_path is not None:
        params["compressed_file_path"] = compressed_file_path
    if delete_directory is not None:
        params["delete_directory"] = delete_directory
    if overwrite is not None:
        params["overwrite"] = overwrite

    response = bridge.call_api(
        "file_system", "compress_directory", method="post", **params
    )

    if isinstance(response, dict) and "error" in response:
        raise ValueError(f"API error: {response['error']}")

    return dict(response) if isinstance(response, dict) else {}


